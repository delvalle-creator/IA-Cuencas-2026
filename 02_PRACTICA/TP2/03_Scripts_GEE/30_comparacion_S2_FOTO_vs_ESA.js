// ---- Composición Sentinel-2 (mediana anual sin nubes) ----
function enmascarar(img){
  var qa=img.select('QA60');
  var m=qa.bitwiseAnd(1<<10).eq(0).and(qa.bitwiseAnd(1<<11).eq(0));
  return img.updateMask(m).divide(10000).copyProperties(img,['system:time_start']);
}
var BANDAS=['B2','B3','B4','B5','B6','B7','B8','B8A','B11','B12'];
var comp=ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED')
  .filterBounds(aoi).filterDate(ee.Date.fromYMD(ANIO,1,1),ee.Date.fromYMD(ANIO,12,31))
  .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE',NUBES_MAX)).map(enmascarar)
  .select(BANDAS).median().clip(aoi);
print('Escenas Sentinel-2 (filtro):', ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED')
  .filterBounds(aoi).filterDate(ee.Date.fromYMD(ANIO,1,1),ee.Date.fromYMD(ANIO,12,31))
  .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE',NUBES_MAX)).size());

// ---- Función: entrena RF y reporta precisión ----
function clasificar(pts, nombre){
  var m=comp.sampleRegions({collection:pts, properties:['clase_id'], scale:10, geometries:true});
  var r=m.randomColumn('a',SEMILLA);
  var tr=r.filter(ee.Filter.lt('a',PROP_TRAIN)), va=r.filter(ee.Filter.gte('a',PROP_TRAIN));
  var clf=ee.Classifier.smileRandomForest(N_ARBOLES).train({features:tr, classProperty:'clase_id', inputProperties:BANDAS});
  var img=comp.classify(clf);
  var mc=va.classify(clf).errorMatrix('clase_id','classification');
  print('===== '+nombre+' =====');
  print('Puntos totales:', pts.size());
  print('Matriz de confusión ('+nombre+'):', mc);
  print('Precisión general (OA) '+nombre+':', mc.accuracy());
  print('Kappa '+nombre+':', mc.kappa());
  return img;
}

